ERROR_STATES = list(
    dict.fromkeys(
        [NO_ERROR, *LEGACY_ERRORS.values(), *ERROR_GROUPS.values(), OTHER_ERROR]
    )
)


def decode_error(value: Any) -> str | None:
    """What the error is, as an `ERROR_STATES` key."""
    if (raw := raw_int(value)) is None or raw < 0:
        return None
    if raw == 0:
        return NO_ERROR
    if raw < 0x100:
        return LEGACY_ERRORS.get(raw, OTHER_ERROR)
    return ERROR_GROUPS.get(raw >> 4, OTHER_ERROR)
